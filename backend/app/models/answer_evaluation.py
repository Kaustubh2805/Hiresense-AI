import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import (
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.database import Base


if TYPE_CHECKING:
    from app.models.session_question import SessionQuestion


class AnswerEvaluation(Base):
    __tablename__ = "answer_evaluations"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # One evaluation belongs to exactly one answered question.
    session_question_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("session_questions.id"),
        nullable=False,
        unique=True,
    )

    # ---------------------------------------------------------
    # Evaluation metadata
    # ---------------------------------------------------------

    # "bank" or "ai_followup"
    evaluation_type: Mapped[str] = mapped_column(
        String,
        nullable=False,
    )

    # Overall score from 1-10
    rating: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # ---------------------------------------------------------
    # Evaluation dimensions
    # ---------------------------------------------------------

    correctness: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    relevance: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    completeness: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    clarity: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    coherence: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    technical_understanding: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ---------------------------------------------------------
    # Candidate-facing feedback
    # ---------------------------------------------------------

    # strong / adequate / partial / weak / incorrect
    verdict: Mapped[str] = mapped_column(
        String,
        nullable=False,
    )

    # Short feedback generated by the evaluation model.
    feedback: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    # ---------------------------------------------------------
    # Timestamp
    # ---------------------------------------------------------

    evaluated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # ---------------------------------------------------------
    # Relationship
    # ---------------------------------------------------------

    session_question: Mapped["SessionQuestion"] = relationship(
        back_populates="evaluation",
    )